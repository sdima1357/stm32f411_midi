# Analysis helpers
# ----------------------------------------------------------------------------
def segment(x, sr, t, dur):
    a = max(0, int(t * sr))
    b = min(len(x), int((t + dur) * sr))
    return x[a:b]


def rms_envelope(x, sr, hop_ms=10.0, win_ms=20.0):
    hop = max(1, int(sr * hop_ms / 1000.0))
    win = max(hop, int(sr * win_ms / 1000.0))
    n = max(1, 1 + (len(x) - win) // hop)
    out = np.empty(n)
    for i in range(n):
        a = i * hop
        out[i] = np.sqrt(np.mean(x[a : a + win] ** 2) + 1e-20)
    return out, hop / sr


def estimate_f0(x, sr):
    if len(x) < 1024:
        return 0.0, 1.0
    try:
        f0, voiced, _ = librosa.pyin(
            x, fmin=40, fmax=min(3000, sr / 2.2), sr=sr, frame_length=2048
        )
        f0v = f0[~np.isnan(f0)]
        if len(f0v) == 0:
            return 0.0, 1.0
        med = float(np.median(f0v))
        std = float(np.std(f0v) / max(med, 1e-9))
        return med, std
    except Exception:
        return 0.0, 1.0


def spectral_flatness(x, sr):
    if len(x) < 512:
        return 0.0
    S = np.abs(librosa.stft(x, n_fft=2048, hop_length=512)) + 1e-12
    flat = np.exp(np.mean(np.log(S), axis=0)) / np.mean(S, axis=0)
    return float(np.mean(flat))


def harmonic_ratio(x, sr, f0):
    if f0 <= 0 or len(x) < 512:
        return 0.0
    y = x * np.hanning(len(x))
    S = np.abs(np.fft.rfft(y))
    freqs = np.fft.rfftfreq(len(y), 1.0 / sr)
    total = np.sum(S**2) + 1e-20
    harm = 0.0
    for k in range(1, 64):
        f = k * f0
        if f >= sr / 2:
            break
        bw = max(1.5 * f0 * 0.15, 2.0 * sr / len(y))
        m = (freqs > f - bw) & (freqs < f + bw)
        harm += np.sum(S[m] ** 2)
    return float(min(1.0, harm / total))


def fit_adsr(x, sr, note_dur, family):
    env, dt = rms_envelope(x, sr)
    if len(env) == 0 or env.max() < 1e-9:
        return ENV_DEFAULTS[family]
    peak = float(env.max())
    peak_i = int(np.argmax(env))
    onset_i = int(np.argmax(env > 0.02 * peak))
    measured_attack = max(0.0, (peak_i - onset_i) * dt)
    a = max(0, int((note_dur - 0.20) / dt))
    b = max(a + 1, int(note_dur / dt))
    b = min(b, len(env))
    sus = float(np.median(env[a:b]) / peak) if b > a else 0.0
    sus = max(0.0, min(1.0, sus))

    da, dd, ds, dr = ENV_DEFAULTS[family]
    alo, ahi = ATTACK_CAPS.get(family, (0.001, 1.0))
    attack = max(alo, min(ahi, max(da, measured_attack)))
    if family in ("strings", "ensemble", "synth_pad", "synth_fx", "ethnic"):
        sustain = max(0.25, min(0.95, sus))
    elif family in ("bass", "brass", "reed", "pipe", "synth_lead"):
        sustain = max(0.45, min(0.95, sus))
    elif family == "organ":
        sustain = 1.0
    else:
        sustain = ds
    # measured decay for sustained families
    if family not in ("piano", "chromatic", "guitar", "organ") and dd > 0:
        target = sustain + 0.1 * (1.0 - sustain)
        idx = np.where(env[peak_i:] < target * peak)[0]
        if len(idx):
            measured_decay = idx[0] * dt
            dd = max(0.03, min(2.0, measured_decay))
    return (attack, dd, sustain, dr)


# ----------------------------------------------------------------------------
# Wavetable extraction (inverse-FFT spectral frames)
# ----------------------------------------------------------------------------
def extract_wt(x, sr, f0, times, rng, frame_len=FRAME_LEN, mips=WT_MIPS):
    kmax = max(mips)
    phases = rng.uniform(0.0, 2.0 * np.pi, kmax)
    frames = []
    for t in times:
        center = int(t * sr)
        win_len = int(max(4.0 * sr / max(f0, 1.0), 1024))
        win_len = min(win_len, 4096, len(x))
        a = max(0, center - win_len // 2)
        b = min(len(x), a + win_len)
        if b - a < 256:
            if frames:
                frames.append(frames[-1].copy())
            else:
                frames.append(np.zeros((len(mips), frame_len), dtype=np.int16))
            continue
        y = x[a:b] * np.hanning(b - a)
        Y = np.fft.rfft(y)
        amps = np.zeros(kmax)
        for k in range(1, kmax + 1):
            f = k * f0
            if f >= sr / 2:
                break
            j = int(round(f * len(y) / sr))
            lo = max(0, j - 2)
            hi = min(len(Y), j + 3)
            jj = lo + int(np.argmax(np.abs(Y[lo:hi])))
            amps[k - 1] = float(np.abs(Y[jj]))
        mip_frames = []
        for K in mips:
            spec = np.zeros(frame_len // 2 + 1, dtype=complex)
            for k in range(1, min(K, kmax) + 1):
                if amps[k - 1] <= 0.0:
                    continue
                spec[k] = amps[k - 1] * np.exp(1j * phases[k - 1]) * frame_len / 2.0
            wave = np.fft.irfft(spec, frame_len)
            peak = float(np.max(np.abs(wave)))
            if peak > 1e-12:
                wave = wave / peak * 0.98
            mip_frames.append(
                np.clip(np.round(wave * 32767.0), -32768, 32767).astype(np.int16)
            )
        frames.append(np.stack(mip_frames))
    return np.stack(frames)  # (n_frames, n_mips, frame_len)


# ----------------------------------------------------------------------------
# 2-operator FM fitting
# ----------------------------------------------------------------------------
def harmonic_amplitudes(x, sr, f0, kmax=32, win_len=2048):
    if len(x) < 256 or f0 <= 0:
        return np.zeros(kmax)
    a = max(0, len(x) // 2 - win_len // 2)
    y = x[a : a + win_len]
    if len(y) < 256:
        y = x
    y = y * np.hanning(len(y))
    Y = np.abs(np.fft.rfft(y))
    freqs = np.fft.rfftfreq(len(y), 1.0 / sr)
    amps = np.zeros(kmax)
    for k in range(1, kmax + 1):
        f = k * f0
        if f >= sr / 2:
            break
        j = int(round(f * len(y) / sr))
        lo = max(0, j - 2)
        hi = min(len(Y), j + 3)
        amps[k - 1] = float(np.max(Y[lo:hi]))
    return amps


def fm_harmonics(ratio, index, kmax=24):
    """Exact harmonic amplitudes of 2-op FM (carrier f0, modulator ratio*f0)."""
    coef = np.zeros(kmax + 1)
    K = int((kmax + 1) / max(ratio, 1e-9)) + 30
    for k in range(-K, K + 1):
        f = 1.0 + k * ratio
        h = abs(f)
        if h < 1.0 or h > kmax:
            continue
        val = jv(k, index)
        if f < 0:
            val = -val
        coef[int(round(h))] += val
    amps = np.abs(coef[1:])
    if amps.max() <= 1e-12:
        return amps
    return amps / amps.max()


def fit_fm(x, sr, f0, ratios=None):
    if f0 <= 0:
        return None
    if ratios is None:
        ratios = FM_RATIOS
    # Use the first 500 ms so the analysis window sits in the early sustain,
    # where plucked/brass attacks still have their full harmonic richness.
    xfit = x[: int(0.5 * sr)] if len(x) > int(0.5 * sr) else x
    target = harmonic_amplitudes(xfit, sr, f0, kmax=24)
    if target.max() <= 1e-12:
        return None
    target = target / target.max()
    # Odd-harmonic-only spectra are much better matched by a 2:1 modulator.
    even = float(np.sum(target[1::2] ** 2))
    odd = float(np.sum(target[0::2] ** 2))
    if 2 in ratios and even < 0.05 * (odd + 1e-12):
        ratios = [2]
    best = (1e9, 1, 0.0)
    for ratio in ratios:
        for idx in np.arange(0.0, FM_INDEX_MAX + 1e-9, FM_INDEX_STEP):
            amps = fm_harmonics(ratio, float(idx), kmax=24)
            w = target + 0.02
            w[0] *= 4.0
            err = float(np.sum(w * (amps - target) ** 2) / (np.sum(w * target**2) + 1e-12))
            if err < best[0]:
                best = (err, ratio, float(idx))
    return best


# ----------------------------------------------------------------------------
# PCM extraction
# ----------------------------------------------------------------------------
def extract_pcm(x, sr, max_sec, target_sr=PCM_SR):
    if len(x) < 32:
        return np.zeros(1, dtype=np.int8)
    y = resample_poly(x, target_sr, sr) if target_sr != sr else x.copy()
    peak = float(np.max(np.abs(y)))
    if peak < 1e-9:
        return np.zeros(1, dtype=np.int8)
    thr = 0.01 * peak
    nz = np.where(np.abs(y) > thr)[0]
    if len(nz) == 0:
        return np.zeros(1, dtype=np.int8)
    start = max(0, nz[0] - int(0.005 * target_sr))
    end = min(len(y), nz[-1] + int(0.010 * target_sr))
    end = min(end, start + int(max_sec * target_sr))
    y = y[start:end].copy()
    if len(y) < 8:
        return np.zeros(1, dtype=np.int8)
    fi = min(int(0.002 * target_sr), len(y) // 4)
    fo = min(int(0.015 * target_sr), len(y) // 4)
    if fi > 0:
        y[:fi] *= np.linspace(0.0, 1.0, fi)
    if fo > 0:
        y[-fo:] *= np.linspace(1.0, 0.0, fo)
    peak = float(np.max(np.abs(y)))
    if peak > 1e-12:
        y = y / peak * 0.90
    return np.clip(np.round(y * 127.0), -127, 127).astype(np.int8)


