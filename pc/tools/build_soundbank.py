def clamp_u8(v):
    return int(max(0, min(255, round(v))))


def inst_to_c(d):
    method = {"PCM": 0, "FM": 1, "WT": 2}[d["method"]]
    root = int(d.get("root", 60))
    frames = int(d["wt"].shape[0]) if d["method"] == "WT" else 0
    flags = int(d.get("flags", 0))
    frame_len = FRAME_LEN if d["method"] == "WT" else 0
    data_off = int(d.get("data_off", 0))
    data_len = int(d.get("data_len", 0))
    attack_ms = int(round(d["attack"] * 1000.0))
    decay_ms = int(round(d["decay"] * 1000.0))
    release_ms = int(round(d["release"] * 1000.0))
    sustain = clamp_u8(d["sustain"] * 255.0)
    gain = clamp_u8(d["gain"] * 255.0)
    fm_ratio = clamp_u8(d.get("fm_ratio", 1.0) * 16.0)
    fm_index = clamp_u8(d.get("fm_index", 0.0) * 16.0)
    fm_feedback = clamp_u8(d.get("fm_feedback", 0.0) * 255.0)
    return (
        f"{{ {method}, {root}, {frames}, {flags}, {frame_len}, "
        f"{data_off}u, {data_len}u, {attack_ms}, {decay_ms}, {release_ms}, "
        f"{sustain}, {gain}, {fm_ratio}, {fm_index}, {fm_feedback}, 0 }}"
    )


def write_c(instruments, drums, wt_pool, pcm_pool, report):
    os.makedirs(DATA_DIR, exist_ok=True)
    hdr = os.path.join(DATA_DIR, "instruments.h")
    with open(hdr, "w") as f:
        f.write("""#ifndef INSTRUMENTS_H
#define INSTRUMENTS_H
#include <stdint.h>

#define GM_NUM_PROGRAMS 128
#define GM_NUM_DRUMS 47
#define GM_DRUM_FIRST 35
#define PCM_SAMPLE_RATE 11025
#define WT_FRAME_LEN 128

/* method: 0=PCM, 1=FM, 2=WT */
typedef struct {
    uint8_t  method;
    uint8_t  root;
    uint8_t  frames;
    uint8_t  flags;       /* bit0 PCM ignore note-off, bit1 PCM no pitch, bit2 WT 2 mips */
    uint16_t frame_len;
    uint32_t data_off;    /* WT: sample index, PCM: byte index */
    uint32_t data_len;    /* WT: samples, PCM: bytes */
    uint16_t attack_ms;
    uint16_t decay_ms;
    uint16_t release_ms;
    uint8_t  sustain;     /* 0..255 */
    uint8_t  gain;        /* 0..255 */
    uint8_t  fm_ratio;    /* ratio * 16 */
    uint8_t  fm_index;    /* index * 16 */
    uint8_t  fm_feedback; /* 0..255 */
    uint8_t  reserved;
} Instrument;

extern const Instrument gm_instruments[GM_NUM_PROGRAMS];
extern const Instrument gm_drums[GM_NUM_DRUMS];
extern const int16_t wt_pool[];
extern const uint32_t wt_pool_len;
extern const int8_t pcm_pool[];
extern const uint32_t pcm_pool_len;
#endif
""")
    with open(os.path.join(DATA_DIR, "instruments.c"), "w") as f:
        f.write('#include "instruments.h"\n\n')
        f.write("const Instrument gm_instruments[GM_NUM_PROGRAMS] = {\n")
        for i, d in enumerate(instruments):
            f.write(
                f"    /* {i:3d} {d.get('family', '?'):10s} {d['method']} */ {inst_to_c(d)},\n"
            )
        f.write("};\n\n")
        f.write("const Instrument gm_drums[GM_NUM_DRUMS] = {\n")
        for i, d in enumerate(drums):
            if d is None:
                f.write(
                    "    { 0xFF, 0, 0, 0, 0, 0u, 0u, 0, 0, 0, 0, 0, 0, 0, 0, 0 },\n"
                )
            else:
                f.write(f"    /* note {DRUM_NOTES[0] + i:3d} */ {inst_to_c(d)},\n")
        f.write("};\n")
    with open(os.path.join(DATA_DIR, "wavetables.c"), "w") as f:
        f.write('#include "instruments.h"\n\n')
        f.write("const uint32_t wt_pool_len = %du;\n" % len(wt_pool))
        f.write("const int16_t wt_pool[%d] = {\n" % max(1, len(wt_pool)))
        if len(wt_pool) == 0:
            f.write("    0\n")
        else:
            for i in range(0, len(wt_pool), 16):
                f.write(
                    "    " + ", ".join(str(int(v)) for v in wt_pool[i : i + 16]) + ",\n"
                )
        f.write("};\n")
    with open(os.path.join(DATA_DIR, "pcm.c"), "w") as f:
        f.write('#include "instruments.h"\n\n')
        f.write("const uint32_t pcm_pool_len = %du;\n" % len(pcm_pool))
        f.write("const int8_t pcm_pool[%d] = {\n" % max(1, len(pcm_pool)))
        if len(pcm_pool) == 0:
            f.write("    0\n")
        else:
            for i in range(0, len(pcm_pool), 32):
                f.write(
                    "    "
                    + ", ".join(str(int(v)) for v in pcm_pool[i : i + 32])
                    + ",\n"
                )
        f.write("};\n")
    with open(os.path.join(ROOT, "build", "soundbank_report.json"), "w") as f:
        json.dump(report, f, indent=2)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--force", action="store_true", help="re-render all fluidsynth files"
    )
    ap.add_argument("--analyze-only", action="store_true")
    ap.add_argument(
        "--programs", type=str, default=None, help="comma list for debugging"
    )
    args = ap.parse_args()

    ensure_dirs()
    t_start = time.time()
    rng = np.random.default_rng(12345)

    programs = list(range(128))
    if args.programs:
        programs = [int(v) for v in args.programs.split(",")]

    instruments = [None] * 128
    methods = {"PCM": 0, "FM": 0, "WT": 0}
    fm_errors = []

    for p in programs:
        x, starts = render_program(p, force=args.force)
        d = build_melodic(p, x, SR, starts, rng)
        if d is None:
            print(f"program {p:3d} {family_of(p):10s}: SILENT -> fallback sine WT")
            # fallback: simple sine wavetable
            wt = np.zeros((3, len(WT_MIPS), FRAME_LEN), dtype=np.int16)
            for fi in range(3):
                for mi, K in enumerate(WT_MIPS):
                    spec = np.zeros(FRAME_LEN // 2 + 1, dtype=complex)
                    spec[1] = FRAME_LEN / 2.0
                    w = np.fft.irfft(spec, FRAME_LEN)
                    wt[fi, mi] = np.clip(
                        np.round(w / np.max(np.abs(w)) * 32000), -32768, 32767
                    )
            d = dict(
                method="WT",
                root=60,
                wt=wt,
                gain=0.2,
                attack=0.01,
                decay=0.0,
                sustain=1.0,
                release=0.2,
                flags=4,
                family=family_of(p),
            )
        instruments[p] = d
        methods[d["method"]] += 1
        if "fm_err" in d:
            fm_errors.append((p, d["fm_err"], d["fm_ratio"], d["fm_index"]))
        print(
            f"program {p:3d} {family_of(p):10s}: {d['method']:3s}"
            + (
                f"  fm_err={d.get('fm_err', 0):.3f} ratio={d.get('fm_ratio')} idx={d.get('fm_index')}"
                if d["method"] == "FM"
                else ""
            )
        )

    print(f"\nmethods: {methods}")
    if fm_errors:
        print("FM fits (best first):")
        for p, e, r, i in sorted(fm_errors, key=lambda z: z[1])[:20]:
            print(f"  prog {p:3d} err={e:.3f} ratio={r} idx={i:.2f}")

    if args.analyze_only:
        return

    # Build pools
    wt_pool = []
    pcm_pool = []
    for d in instruments:
        if d["method"] == "WT":
            d["data_off"] = len(wt_pool)
            arr = d["wt"].reshape(-1)
            d["data_len"] = len(arr)
            wt_pool.extend(int(v) for v in arr)
        elif d["method"] == "PCM":
            d["data_off"] = len(pcm_pool)
            d["data_len"] = len(d["pcm"])
            pcm_pool.extend(int(v) for v in d["pcm"])

    # Drums
    dx, dstarts = render_drums(force=args.force)
    drums = []
    for note, t in zip(DRUM_NOTES, dstarts):
        d = build_drum(note, dx, SR, t)
        if d is not None:
            d["data_off"] = len(pcm_pool)
            d["data_len"] = len(d["pcm"])
            pcm_pool.extend(int(v) for v in d["pcm"])
        drums.append(d)

    # Report
    wt_bytes = len(wt_pool) * 2
    pcm_bytes = len(pcm_pool)
    inst_bytes = (128 + 47) * 28
    total = wt_bytes + pcm_bytes + inst_bytes
    report = {
        "methods": methods,
        "wt_samples": len(wt_pool),
        "wt_bytes": wt_bytes,
        "pcm_bytes": pcm_bytes,
        "instrument_bytes": inst_bytes,
        "data_total_bytes": total,
        "flash_budget": 512 * 1024,
        "render_seconds": round(time.time() - t_start, 1),
        "fm_fits": [
            {"program": p, "error": e, "ratio": r, "index": i}
            for p, e, r, i in fm_errors
        ],
    }
    print(f"\nWT: {wt_bytes / 1024:.1f} KiB ({len(wt_pool)} samples)")
    print(f"PCM: {pcm_bytes / 1024:.1f} KiB")
    print(f"Instrument tables: {inst_bytes / 1024:.1f} KiB")
    print(f"TOTAL DATA: {total / 1024:.1f} KiB / 512 KiB")
    if total > 470 * 1024:
        print("WARNING: data exceeds comfortable flash budget")

    write_c(instruments, drums, wt_pool, pcm_pool, report)
    print(f"Wrote C tables to {DATA_DIR}")
    print(f"Elapsed {time.time() - t_start:.1f}s")


if __name__ == "__main__":
    main()
