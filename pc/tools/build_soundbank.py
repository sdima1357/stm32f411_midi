# Instrument construction
# ----------------------------------------------------------------------------
def choose_analysis_note(x, sr, starts):
    """Pick the note closest to C4 with a stable pitch and good level."""
    best = None
    for note, t in zip(MELODIC_NOTES, starts):
        s = segment(x, sr, t, NOTE_DUR)
        if len(s) < 1024:
            continue
        f0, f0std = estimate_f0(s, sr)
        rms = float(np.sqrt(np.mean(s**2)))
        score = abs(note - 60) * 0.05 + f0std * 2.0 - min(rms, 0.2) * 2.0
        if f0 <= 0:
            score += 10.0
        if best is None or score < best[0]:
            best = (score, note, t, s, f0, f0std, rms)
    if best is None:
        return None
    return best[1:]


def build_melodic(program, x, sr, starts, rng):
    fam = family_of(program)
    pick = choose_analysis_note(x, sr, starts)
    if pick is None:
        return None
    note, t, s, f0, f0std, rms = pick
    flat = spectral_flatness(s, sr)
    hratio = harmonic_ratio(s, sr, f0)
    attack, decay, sustain, release = fit_adsr(s, sr, NOTE_DUR, fam)

    # Percussive / SFX families are always PCM.
    if fam in ("percussive", "sfx"):
        pcm = extract_pcm(
            s, sr, PCM_MAX_SEC_PERC if fam == "percussive" else PCM_MAX_SEC_SFX
        )
        gain = 0.40 * np.clip(rms / 0.04, 0.6, 1.4)
        return dict(
            method="PCM",
            root=note,
            pcm=pcm,
            gain=gain,
            attack=0.002,
            decay=0.0,
            sustain=1.0,
            release=0.02,
            flags=1 | (2 if fam == "sfx" else 0),
            family=fam,
        )

    # Try FM for families where it is musically sensible.
    fm = None
    if fam in (
        "bass",
        "brass",
        "reed",
        "pipe",
        "synth_lead",
        "organ",
        "chromatic",
        "synth_fx",
    ):
        if fam in ("bass", "brass", "reed", "pipe"):
            fm_ratios = [1]
        else:
            fm_ratios = [1, 2, 3, 4]
        fm = fit_fm(s, sr, f0, fm_ratios)
    if fm is not None and fm[0] < FM_THRESHOLD:
        err, ratio, index = fm
        gain = 0.24 * np.clip(rms / 0.04, 0.6, 1.4)
        return dict(
            method="FM",
            root=note,
            fm_ratio=ratio,
            fm_index=index,
            fm_feedback=0.0,
            gain=gain,
            attack=attack,
            decay=decay,
            sustain=sustain,
            release=release,
            flags=0,
            family=fam,
            fm_err=err,
        )

    # Otherwise spectral wavetable.
    times = FRAME_TIMES.get(fam, FRAME_TIMES["synth_lead"])
    # shift frames slightly past the attack so the first frame is not silence
    t0 = min(0.20, attack * 0.5)
    times = [min(1.10, t0 + dt) for dt in times]
    wt = extract_wt(s, sr, f0, times, rng)
    gain = 0.24 * np.clip(rms / 0.04, 0.6, 1.4)
    return dict(
        method="WT",
        root=note,
        wt=wt,
        gain=gain,
        attack=attack,
        decay=decay,
        sustain=sustain,
        release=release,
        flags=4,
        family=fam,
        f0=f0,
        hratio=hratio,
        flatness=flat,
    )


def build_drum(note, x, sr, t):
    s = segment(x, sr, t, DRUM_DUR + 0.15)
    if len(s) < 32 or np.max(np.abs(s)) < 1e-6:
        return None
    pcm = extract_pcm(s, sr, PCM_MAX_SEC_DRUM)
    rms = float(np.sqrt(np.mean(s**2)))
    gain = 0.50 * np.clip(rms / 0.04, 0.5, 1.3)
    return dict(
        method="PCM",
        root=note,
        pcm=pcm,
        gain=gain,
        attack=0.001,
        decay=0.0,
        sustain=1.0,
        release=0.02,
        flags=1 | 2,
        family="drum",
    )


