def ensure_dirs():
    os.makedirs(RENDER_DIR, exist_ok=True)
    os.makedirs(DATA_DIR, exist_ok=True)


def make_midi(path, program, notes, dur, gap, channel=0):
    mid = mido.MidiFile(type=0, ticks_per_beat=480)
    tr = mido.MidiTrack()
    mid.tracks.append(tr)
    tps = 480 * 2.0  # 120 BPM
    tr.append(mido.MetaMessage("set_tempo", tempo=mido.bpm2tempo(120), time=0))
    if channel != 9:
        tr.append(
            mido.Message("program_change", program=program, channel=channel, time=0)
        )
    starts = []
    now = 0.0
    for i, n in enumerate(notes):
        starts.append(now)
        dticks = int(round(dur * tps))
        gticks = int(round(gap * tps)) if i + 1 < len(notes) else 0
        tr.append(
            mido.Message("note_on", note=n, velocity=100, channel=channel, time=0)
        )
        tr.append(
            mido.Message("note_off", note=n, velocity=0, channel=channel, time=dticks)
        )
        if gticks:
            tr.append(mido.MetaMessage("text", text="", time=gticks))
        now += dur + gap
    mid.save(path)
    return starts


def render_file(mid_path, wav_path):
    cmd = [
        "fluidsynth",
        "-ni",
        "-F",
        wav_path,
        "-r",
        str(SR),
        "-g",
        "0.7",
        "-o",
        "synth.reverb.active=0",
        "-o",
        "synth.chorus.active=0",
        "-o",
        "synth.polyphony=64",
        SF2,
        mid_path,
    ]
    subprocess.run(
        cmd, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL
    )


def load_mono(path):
    x, sr = sf.read(path, always_2d=True)
    x = x.mean(axis=1)
    if sr != SR:
        x = resample_poly(x, SR, sr)
    return x.astype(np.float64)


def render_program(program, force=False):
    tag = f"prog_{program:03d}"
    midp = os.path.join(RENDER_DIR, tag + ".mid")
    wavp = os.path.join(RENDER_DIR, tag + ".wav")
    if force or not os.path.exists(wavp) or os.path.getsize(wavp) < 1000:
        starts = make_midi(midp, program, MELODIC_NOTES, NOTE_DUR, NOTE_GAP)
        render_file(midp, wavp)
    else:
        starts = [i * (NOTE_DUR + NOTE_GAP) for i in range(len(MELODIC_NOTES))]
    return load_mono(wavp), starts


def render_drums(force=False):
    tag = "drums"
    midp = os.path.join(RENDER_DIR, tag + ".mid")
    wavp = os.path.join(RENDER_DIR, tag + ".wav")
    if force or not os.path.exists(wavp) or os.path.getsize(wavp) < 1000:
        starts = make_midi(midp, 0, DRUM_NOTES, DRUM_DUR, DRUM_GAP, channel=9)
        render_file(midp, wavp)
    else:
        starts = [i * (DRUM_DUR + DRUM_GAP) for i in range(len(DRUM_NOTES))]
    return load_mono(wavp), starts


