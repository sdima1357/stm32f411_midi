"""
build_soundbank.py

Offline GM soundbank builder for the STM32F411 12-voice synth.

Pipeline:
  1. Render isolated notes for every GM program with fluidsynth (dry, 22.05 kHz).
  2. Analyse each instrument and choose the cheapest method that fits:
       - PCM  : one-shot 8-bit samples (drums, percussive, SFX)
       - FM   : 2-operator FM fitted to the harmonic spectrum
       - WT   : spectral wavetable frames generated by inverse FFT
  3. Emit compact C tables for the MCU (flash-resident const arrays).

The output is deterministic and cached under build/render.
"""

